#!/usr/bin/env python3
"""Pack only the glyphs the game uses from Fusion Pixel Font 12px into js/data/fontdata.js.

Usage: python3 -I tools/build_font.py <path-to-fusion-pixel-12px-proportional-zh_hans.bdf>
Re-run whenever new Chinese text is added; tests/run.js fails if a glyph is missing.
"""
import base64
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCAN_DIRS = ['js']
ASCII = ''.join(chr(c) for c in range(32, 127))
EXTRA = '□·…—，。！？、；：「」『』（）《》“”‘’～×→←↑↓▲▼★☆°%+-/'


def used_chars():
    chars = set(ASCII) | set(EXTRA)
    for d in SCAN_DIRS:
        for base, _, files in os.walk(os.path.join(ROOT, d)):
            for name in files:
                if not name.endswith('.js') or name == 'fontdata.js':
                    continue
                with open(os.path.join(base, name), encoding='utf8') as fh:
                    src = fh.read()
                # Comments are not displayed text, so they should not add to the font size.
                src = re.sub(r'^\s*//.*$', '', src, flags=re.M)
                src = re.sub(r'\s//\s.*$', '', src, flags=re.M)
                for ch in src:
                    if ord(ch) > 127:
                        chars.add(ch)
    return chars


def parse_bdf(path, wanted):
    glyphs, ascent, descent = {}, 11, 1
    with open(path, encoding='latin-1') as fh:
        cur = None
        in_bitmap = False
        for line in fh:
            line = line.strip()
            if line.startswith('FONT_ASCENT'):
                ascent = int(line.split()[1])
            elif line.startswith('FONT_DESCENT'):
                descent = int(line.split()[1])
            elif line.startswith('STARTCHAR'):
                cur = {'rows': []}
            elif line.startswith('ENCODING') and cur is not None:
                cur['cp'] = int(line.split()[1])
            elif line.startswith('DWIDTH') and cur is not None:
                cur['adv'] = int(line.split()[1])
            elif line.startswith('BBX') and cur is not None:
                cur['bbx'] = [int(v) for v in line.split()[1:5]]
            elif line == 'BITMAP':
                in_bitmap = True
            elif line == 'ENDCHAR':
                in_bitmap = False
                if cur and cur.get('cp', -1) >= 0 and chr(cur['cp']) in wanted:
                    glyphs[chr(cur['cp'])] = cur
                cur = None
            elif in_bitmap and cur is not None:
                cur['rows'].append(line)
    return glyphs, ascent, descent


def main():
    bdf = sys.argv[1]
    wanted = used_chars()
    glyphs, ascent, descent = parse_bdf(bdf, wanted)
    cell = ascent + descent
    missing = sorted(wanted - set(glyphs))
    if missing:
        print('NOT IN FONT:', ''.join(missing))

    chars, widths, adv, bits, grids = [], [], [], [], []
    for ch in sorted(glyphs):
        g = glyphs[ch]
        w, h, xo, yo = g['bbx']
        cw = max(0, xo) + w
        grid = [[0] * cw for _ in range(cell)]
        top = ascent - (h + yo)
        for j, hexrow in enumerate(g['rows']):
            val = int(hexrow, 16) if hexrow else 0
            nbits = len(hexrow) * 4
            for i in range(w):
                if (val >> (nbits - 1 - i)) & 1:
                    y = top + j
                    x = max(0, xo) + i
                    if 0 <= y < cell:
                        grid[y][x] = 1
        chars.append(ch)
        widths.append(cw)
        adv.append(g['adv'])
        grids.append(grid)

    # The BDF cell includes line spacing. Crop to the rows that actually hold ink.
    used = [y for g in grids for y, row in enumerate(g) if any(row)]
    y0, y1 = min(used), max(used)
    for g in grids:
        for row in g[y0:y1 + 1]:
            bits.extend(row)
    cell = y1 - y0 + 1

    packed = bytearray()
    for i in range(0, len(bits), 8):
        chunk = bits[i:i + 8]
        val = 0
        for b in chunk:
            val = (val << 1) | b
        packed.append(val << (8 - len(chunk)))

    out = os.path.join(ROOT, 'js', 'data', 'fontdata.js')
    with open(out, 'w', encoding='utf8') as fh:
        fh.write('// Generated by tools/build_font.py. Subset of Fusion Pixel Font 12px (SIL OFL 1.1).\n')
        fh.write('module.exports = ')
        json.dump({'h': cell, 'chars': ''.join(chars), 'widths': widths, 'adv': adv,
                   'bits': base64.b64encode(bytes(packed)).decode()}, fh, ensure_ascii=False,
                  separators=(',', ':'))
        fh.write(';\n')
    print(f'{len(chars)} glyphs, cell {cell}px, {os.path.getsize(out) // 1024} KB')


if __name__ == '__main__':
    main()
